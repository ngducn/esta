import { existsSync, mkdtempSync, readFileSync, writeFileSync } from 'node:fs';
import { createRequire } from 'node:module';
import { tmpdir } from 'node:os';
import { join } from 'node:path';
import { fileURLToPath, pathToFileURL } from 'node:url';
import {
  breakpoints,
  colors,
  densities,
  focusRing,
  fontWeight,
  layout,
  leading,
  motion,
  overlays,
  phoneCardPx,
  radius,
  shadows,
  sizes,
  strokeStrongPx,
  spacing,
  textScales,
  brandHeadlines,
  typeStyles,
  type Theme,
} from '../apps/web/src/design/tokens.ts';

const tokensCssPath = fileURLToPath(new URL('../apps/web/src/styles/tokens.css', import.meta.url));
const webRoot = fileURLToPath(new URL('../apps/web/', import.meta.url));
const cnTablesPath = join(webRoot, 'src/lib/cn-tables.ts');

const ROOT_PX = 16;
const rem = (px: number) => (px === 0 ? '0' : `${px / ROOT_PX}rem`);
const block = (selector: string, lines: string[], indent = '') =>
  [`${indent}${selector} {`, ...lines.map((line) => `${indent}  ${line}`), `${indent}}`].join('\n');

/** Light whatever the system says; dark only when the member chose it, which the server writes as data-theme. */
const chosenDark = '[data-theme="dark"]';

const themed = (theme: Theme) => [
  ...Object.entries(colors).map(([name, value]) => `--${name}: ${value[theme]};`),
  ...Object.entries(overlays).map(([name, value]) => `--${name}: ${value[theme]};`),
];

const densityVars = (density: keyof typeof densities) => Object.entries(densities[density]).map(([name, px]) => `--${name}: ${rem(px)};`);

function renderTokensCss(): string {
  const root = [
    '--text-scale: 1;',
    ...themed('light'),
    ...Object.entries(motion.duration).map(([name, ms]) => `--duration-${name}: ${ms}ms;`),
    `--focus-width: ${focusRing.widthPx}px;`,
    `--focus-offset: ${focusRing.offsetPx}px;`,
    `--stroke-strong: ${strokeStrongPx}px;`,
    ...densityVars('comfortable'),
  ];
  const inlineTheme = [
    '--color-*: initial;',
    ...[...Object.keys(colors), ...Object.keys(overlays)].map((name) => `--color-${name}: var(--${name});`),
    '--text-*: initial;',
    ...Object.entries(typeStyles).flatMap(([name, style]) => [
      `--text-${name}: ${rem(style.px)};`,
      `--text-${name}--line-height: ${rem(style.linePx)};`,
      // Body weight stays inherited, so a 400 style never thins a heading or a semibold parent.
      ...(style.weight === fontWeight.normal ? [] : [`--text-${name}--font-weight: ${style.weight};`]),
      ...('trackingEm' in style ? [`--text-${name}--letter-spacing: ${style.trackingEm}em;`] : []),
    ]),
    ...Object.entries(brandHeadlines).flatMap(([name, style]) => [
      `--text-${name}: ${style.vw === 0 ? rem(style.maxPx) : `clamp(${rem(style.minPx)}, ${style.vw}vw, ${rem(style.maxPx)})`};`,
      `--text-${name}--line-height: ${style.leading};`,
      `--text-${name}--font-weight: ${style.weight};`,
      `--text-${name}--letter-spacing: ${style.trackingEm}em;`,
    ]),
    '--leading-*: initial;',
    ...Object.entries(leading).map(([name, value]) => `--leading-${name}: ${value};`),
    '--breakpoint-*: initial;',
    ...Object.entries(breakpoints).map(([name, px]) => `--breakpoint-${name}: ${rem(px)};`),
    `--spacing-touch: ${rem(spacing.touchPx)};`,
    ...Object.keys(densities.comfortable).map((name) => `--spacing-${name}: var(--${name});`),
    ...Object.entries(sizes).map(([name, px]) => `--spacing-${name}: ${rem(px)};`),
    ...(['sidebar', 'rail', 'bottom-nav'] as const).map((name) => `--spacing-${name}: ${rem(layout[name])};`),
    ...Object.entries(layout)
      .filter(([name]) => !['sidebar', 'rail', 'bottom-nav'].includes(name))
      .map(([name, px]) => `--container-${name}: ${rem(px)};`),
    '--ease-*: initial;',
    ...Object.entries(motion.ease).map(([name, value]) => `--ease-${name}: ${value};`),
    '--font-weight-*: initial;',
    ...Object.entries(fontWeight).map(([name, value]) => `--font-weight-${name}: ${value};`),
    '--font-serif: initial;',
    '--font-mono: initial;',
    '--font-sans: var(--font-inter);',
    '--font-display: var(--font-inter-display, var(--font-inter));',
    '--radius-*: initial;',
    ...Object.entries(radius).map(([name, px]) => `--radius-${name}: ${px === radius.full ? 'calc(infinity * 1px)' : `${px}px`};`),
  ];
  return [
    '/* Generated by scripts/build-tokens.ts from apps/web/src/design/tokens.ts. Edit tokens.ts, then run pnpm tokens:build. */',
    '',
    block(':root', [...root, 'color-scheme: light;']),
    '',
    block(chosenDark, [...themed('dark'), ...Object.entries(shadows).map(([name, value]) => `--shadow-${name}: ${value.dark};`), 'color-scheme: dark;']),
    '',
    '/* dark: follows the dark palette selector, so it obeys the esta_theme cookie and never the system setting. */',
    `@custom-variant dark (&:where(${chosenDark}, ${chosenDark} *));`,
    '',
    block('@theme inline', inlineTheme),
    '',
    '/* Not inline, so utilities read var(--shadow-*) and the dark theme can retune each one. */',
    block('@theme', [`--spacing: ${rem(spacing.unitPx)};`, '--shadow-*: initial;', ...Object.entries(shadows).map(([name, value]) => `--shadow-${name}: ${value.light};`)]),
    '',
    block(':root[data-density="compact"]', densityVars('compact')),
    '',
    '/* Gọn tightens for a mouse; a finger still gets the touch minimum. */',
    block('@media (pointer: coarse)', [block(':root[data-density="compact"]', [`--control-h: ${rem(Math.max(densities.compact['control-h'], spacing.touchPx))};`], '  ').trimStart()]),
    '',
    block(`@media (width < ${rem(breakpoints.sm)})`, [block(':root', [`--card-pad: ${rem(phoneCardPx)};`], '  ').trimStart()]),
    '',
    ...textScales
      .filter((scale) => scale !== 100)
      .map((scale) => block(`:root[data-text-scale="${scale}"]`, [`--text-scale: ${scale / 100};`])),
    '',
  ].join('\n');
}

/** Precompiled tables let the browser ship `cn/engine` instead of `cn/config`'s runtime compiler. */
async function renderCnTables(): Promise<string> {
  const require = createRequire(join(webRoot, 'package.json'));
  const { build } = (await import(pathToFileURL(require.resolve('cn/build')).href)) as {
    build: (options: { cwd: string; css: string; full: true; out: string }) => Promise<{ source: string }>;
  };
  const out = join(mkdtempSync(join(tmpdir(), 'esta-cn-')), 'cn-tables.ts');
  const { source } = await build({ cwd: webRoot, css: 'src/app/globals.css', full: true, out });
  return source;
}

function isStale(path: string, expected: string): boolean {
  return (existsSync(path) ? readFileSync(path, 'utf8') : '') !== expected;
}

async function main(): Promise<void> {
  const css = renderTokensCss();
  if (process.argv.includes('--check')) {
    if (isStale(tokensCssPath, css) || isStale(cnTablesPath, await renderCnTables())) {
      console.error('tokens.css or cn-tables.ts is stale. Run pnpm tokens:build and commit the result.');
      process.exit(1);
    }
    console.log('tokens.css and cn-tables.ts match tokens.ts');
    return;
  }
  writeFileSync(tokensCssPath, css);
  writeFileSync(cnTablesPath, await renderCnTables());
  console.log(`wrote ${tokensCssPath} and ${cnTablesPath}`);
}

if (import.meta.url === pathToFileURL(process.argv[1] ?? '').href) await main();
