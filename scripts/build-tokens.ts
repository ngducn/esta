import { existsSync, mkdtempSync, readFileSync, writeFileSync } from 'node:fs';
import { createRequire } from 'node:module';
import { tmpdir } from 'node:os';
import { join } from 'node:path';
import { fileURLToPath, pathToFileURL } from 'node:url';
import { colors, densities, fontWeight, leading, motion, radius, shadows, shell, spacing, textScales, typeScale, type Oklch, type Theme } from '../apps/web/src/design/tokens.ts';

const tokensCssPath = fileURLToPath(new URL('../apps/web/src/styles/tokens.css', import.meta.url));
const webRoot = fileURLToPath(new URL('../apps/web/', import.meta.url));
const cnTablesPath = join(webRoot, 'src/lib/cn-tables.ts');

const ROOT_PX = 16;
const rem = (px: number) => (px === 0 ? '0' : `${px / ROOT_PX}rem`);
const oklch = ([l, c, h]: Oklch) => `oklch(${l}% ${c} ${h})`;
const block = (selector: string, lines: string[], indent = '') =>
  [`${indent}${selector} {`, ...lines.map((line) => `${indent}  ${line}`), `${indent}}`].join('\n');

/** Light whatever the system says; dark only when the member chose it, which the server writes as data-theme. */
const chosenDark = '[data-theme="dark"]';

const colorVars = (theme: Theme) => Object.entries(colors).map(([name, value]) => `--${name}: ${oklch(value[theme])};`);

function renderTokensCss(): string {
  const root = [
    '--text-scale: 1;',
    ...colorVars('light'),
    ...Object.entries(motion.duration).map(([name, ms]) => `--duration-${name}: ${ms}ms;`),
  ];
  const theme = [
    '--color-*: initial;',
    ...Object.keys(colors).map((name) => `--color-${name}: var(--${name});`),
    '--text-*: initial;',
    ...Object.entries(typeScale).flatMap(([name, step]) => [
      `--text-${name}: ${rem(step.px)};`,
      `--text-${name}--line-height: ${step.leading};`,
    ]),
    '--leading-*: initial;',
    ...Object.entries(leading).map(([name, value]) => `--leading-${name}: ${value};`),
    `--spacing-touch: ${rem(spacing.touchPx)};`,
    `--spacing-sidebar: ${rem(shell.sidebarPx)};`,
    `--container-content: ${rem(shell.contentPx)};`,
    '--ease-*: initial;',
    `--ease-standard: ${motion.ease};`,
    '--font-weight-*: initial;',
    ...Object.entries(fontWeight).map(([name, value]) => `--font-weight-${name}: ${value};`),
    '--font-serif: initial;',
    '--font-mono: initial;',
    '--font-sans: var(--font-plus-jakarta-sans);',
    '--radius-*: initial;',
    ...Object.entries(radius).map(([name, px]) => `--radius-${name}: ${px === radius.full ? 'calc(infinity * 1px)' : rem(px)};`),
    '--shadow-*: initial;',
    ...Object.entries(shadows).map(([name, value]) => `--shadow-${name}: ${value};`),
  ];
  return [
    '/* Generated by scripts/build-tokens.ts from apps/web/src/design/tokens.ts. Edit tokens.ts, then run pnpm tokens:build. */',
    '',
    block(':root', [...root, 'color-scheme: light;']),
    '',
    block(chosenDark, [...colorVars('dark'), 'color-scheme: dark;']),
    '',
    '/* dark: follows the dark palette selector, so it obeys the esta_theme cookie and never the system setting. */',
    `@custom-variant dark (&:where(${chosenDark}, ${chosenDark} *));`,
    '',
    block('@theme inline', theme),
    '',
    '/* Not inline, so utilities read var(--spacing) and data-density can retune every one of them. */',
    block('@theme', [`--spacing: ${rem(spacing.unitPx)};`]),
    '',
    ...Object.entries(densities)
      .filter(([, density]) => density.unitPx !== spacing.unitPx)
      .map(([name, density]) => block(`:root[data-density="${name}"]`, [`--spacing: ${rem(density.unitPx)};`])),
    '',
    ...textScales
      .filter((scale) => scale !== 100)
      .map((scale) => block(`:root[data-text-scale="${scale}"]`, [`--text-scale: ${scale / 100};`])),
    '',
  ].join('\n');
}

/** Precompiled tables let the browser ship `cn/engine` instead of `cn/config`'s runtime compiler. */
async function renderCnTables(): Promise<string> {
  const require = createRequire(join(webRoot, 'package.json'));
  const { build } = (await import(pathToFileURL(require.resolve('cn/build')).href)) as {
    build: (options: { cwd: string; css: string; full: true; out: string }) => Promise<{ source: string }>;
  };
  const out = join(mkdtempSync(join(tmpdir(), 'esta-cn-')), 'cn-tables.ts');
  const { source } = await build({ cwd: webRoot, css: 'src/app/globals.css', full: true, out });
  return source;
}

function isStale(path: string, expected: string): boolean {
  return (existsSync(path) ? readFileSync(path, 'utf8') : '') !== expected;
}

async function main(): Promise<void> {
  const css = renderTokensCss();
  if (process.argv.includes('--check')) {
    if (isStale(tokensCssPath, css) || isStale(cnTablesPath, await renderCnTables())) {
      console.error('tokens.css or cn-tables.ts is stale. Run pnpm tokens:build and commit the result.');
      process.exit(1);
    }
    console.log('tokens.css and cn-tables.ts match tokens.ts');
    return;
  }
  writeFileSync(tokensCssPath, css);
  writeFileSync(cnTablesPath, await renderCnTables());
  console.log(`wrote ${tokensCssPath} and ${cnTablesPath}`);
}

if (import.meta.url === pathToFileURL(process.argv[1] ?? '').href) await main();
