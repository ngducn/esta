import type { Instant } from '../../../packages/core/src/index.ts';

export type SqlValue =
  | string
  | number
  | boolean
  | null
  | undefined
  | readonly SqlValue[]
  | { readonly [key: string]: SqlValue };

export type SqlRow = Readonly<Record<string, SqlValue>>;

export type TableRows = { readonly table: string; readonly upsert?: boolean; readonly rows: readonly SqlRow[] };

const STAMPED_COLUMNS = ['created_at', 'updated_at'] as const;

function quote(text: string): string {
  return `'${text.replaceAll("'", "''")}'`;
}

function arrayLiteral(items: readonly SqlValue[]): string {
  const elements = items.map((item) => {
    if (typeof item === 'number' && Number.isFinite(item)) return String(item);
    if (typeof item !== 'string') throw new Error(`A Postgres array holds text or numbers, got ${JSON.stringify(item)}`);
    return `"${item.replaceAll('\\', '\\\\').replaceAll('"', '\\"')}"`;
  });
  return `{${elements.join(',')}}`;
}

function literal(value: SqlValue): string {
  if (value === undefined) return 'default';
  if (value === null) return 'null';
  if (typeof value === 'boolean') return String(value);
  if (typeof value === 'number') {
    if (!Number.isFinite(value)) throw new Error(`Seed numbers must be finite, got ${value}`);
    return String(value);
  }
  if (typeof value === 'string') return quote(value);
  if (Array.isArray(value)) return quote(arrayLiteral(value));
  return quote(JSON.stringify(value));
}

function insert({ table, upsert, rows }: TableRows, stamp: Instant): string {
  const columns = [...new Set(rows.flatMap((row) => Object.keys(row)))];
  const stamped = STAMPED_COLUMNS.filter((column) => !columns.includes(column));
  const values = rows.map(
    (row) => `  (${[...columns.map((column) => literal(row[column])), ...stamped.map(() => quote(stamp))].join(', ')})`,
  );
  const updated = columns.filter((column) => column !== 'id' && column !== 'created_at');
  const conflict = upsert === true ? `\non conflict (id) do update set ${updated.map((column) => `${column} = excluded.${column}`).join(', ')}` : '';
  return `insert into ${table} (${[...columns, ...stamped].join(', ')}) values\n${values.join(',\n')}${conflict};\n`;
}

/** `tail` runs after every table, for rows the database itself writes from them, such as invoices. */
export function renderSeed(tables: readonly TableRows[], stamp: Instant, tail = ''): string {
  const statements = tables.filter((table) => table.rows.length > 0).map((table) => insert(table, stamp));
  return [
    '-- Generated by supabase/seed/generator. Do not edit; run pnpm db:reset.',
    "select set_config('esta.actor', 'system:seed', true);",
    'insert into private.local_stack default values on conflict do nothing;',
    '',
    ...statements,
    tail,
  ].join('\n');
}
